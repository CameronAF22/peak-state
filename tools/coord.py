def _deny(message: str) -> int:
    print(f"[coord] {message}", file=sys.stderr)
    return 2


def hook_session_start(payload: dict) -> int:
    cfg = load_lanes()
    lanes = lane_map(cfg)
    state = load_state()
    if payload.get("source") in (None, "startup") or "startHead" not in state:
        state["startHead"] = head_sha()
        state["sessionStartedAt"] = now_iso()
        save_state(state)
    fetched = fetch(force=True)
    lane = my_lane()
    if lane and lane in lanes:
        touch_session(lane)
    view = collect()
    ref = session_ref()
    out = ["# Peak State coordination · required protocol (CLAUDE.md, coord/README.md)", ""]
    if lane and lane in lanes:
        info = lanes[lane]
        out += [
            f"You are lane `{lane}` ({info['name']}) in session {ref['url'] or ref['id']} on branch {ref['branch']}.",
            f"Brief: docs/hackathon/lanes/{lane}.md · spec: spec/{lane}.md · you own: {', '.join(info['owns'])}",
        ]
    else:
        out += [
            "You have NOT claimed a lane, so edits are blocked. If your task names a lane, claim it first:",
            "  python3 tools/coord.py claim <lane> --purpose '<one line>'",
            "Lanes: " + "; ".join(f"{l['id']} ({l['name']})" for l in cfg["lanes"]),
        ]
    out += ["", render_board(view, lane)]
    if lane:
        msgs = inbox_for(view, lane)[:8]
        if msgs:
            out += ["", f"INBOX for {lane} (newest first)"] + [render_message(m) for m in msgs]
            update_state(seen=sorted(set(load_state().get("seen", [])) | {m["id"] for m in msgs})[-1000:])
    out += ["", LOOP_TEXT]
    if not fetched:
        out.append("(git fetch failed; the board shows the last fetched state)")
    print("\n".join(out))
    return 0


def hook_prompt(payload: dict) -> int:
    lane = my_lane()
    if not lane:
        print("[coord] No lane claimed yet: python3 tools/coord.py claim <lane> --purpose '…' before editing.")
        return 0
    fetch()
    view = collect()
    state = load_state()
    seen = set(state.get("seen", []))
    new = [m for m in inbox_for(view, lane) if m["id"] not in seen]
    lines = []
    if new:
        lines.append(f"[coord] {len(new)} new message(s) for lane {lane}:")
        lines += [render_message(m) for m in new[:6]]
        update_state(seen=sorted(seen | {m["id"] for m in new})[-1000:])
    status = view["status"].get(lane)
    updated = parse_iso((status or {}).get("updatedAt"))
    if status is None or (updated and (datetime.now(timezone.utc) - updated).total_seconds() > STATUS_STALE_MINUTES * 60):
        lines.append(f"[coord] Lane status is {ago((status or {}).get('updatedAt'))}. Refresh it when you reach a milestone: python3 tools/coord.py status --summary '…'")
    if lines:
        print("\n".join(lines))
    return 0


def hook_pre_edit(payload: dict) -> int:
    tool_input = payload.get("tool_input") or {}
    raw = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not raw:
        return 0
    target = Path(raw)
    if not target.is_absolute():
        target = Path(payload.get("cwd") or ROOT) / target
    try:
        path = target.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return 0  # outside the repository
    if path.startswith(".git/"):
        return 0
    cfg = load_lanes()
    if is_generated(path, cfg):
        return _deny(f"{path} is a coordination record or generated spec. Write it with python3 tools/coord.py (decide, status, msg, build), never by hand.")
    lane = my_lane()
    if not lane:
        return _deny("Claim a lane before editing: python3 tools/coord.py claim <lane> --purpose '…'. Lanes: " + ", ".join(lane_map(cfg)))
    owner = owner_of(path, cfg)
    if owner == lane or path in load_state().get("borrowed", []):
        return 0
    if owner is None:
        if lane == "coord":
            return 0
        owns = ", ".join(lane_map(cfg).get(lane, {}).get("owns", []))
        return _deny(f"{path} is outside every lane's paths. Put it under your paths ({owns}) or ask coord: python3 tools/coord.py msg coord --subject 'ownership for {path}' --body '…'")
    return _deny(
        f"{path} belongs to lane '{owner}'. Ask them: python3 tools/coord.py msg {owner} --subject '…' --body '…'. "
        f"If the change is agreed, record it and unlock the file: python3 tools/coord.py borrow {path} --reason '…'"
    )


PUSH_RE = re.compile(
    r"(?:^|[;&|(\n]|&&|\|\|)\s*(?:[A-Za-z_][A-Za-z0-9_]*=\S*\s+)*git(?:\s+-C\s+\S+|\s+-c\s+\S+|\s+--[a-z-]+(?:=\S+)?)*\s+push\b"
)
HEREDOC_RE = re.compile(r"<<-?\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?")


def strip_heredocs(command: str) -> str:
    """Drop heredoc bodies so file contents that mention `git push` are not commands."""
    kept, terminator = [], None
    for line in command.split("\n"):
        if terminator:
            if line.strip() == terminator:
                terminator = None
            continue
        kept.append(line)
        match = HEREDOC_RE.search(line)
        if match:
            terminator = match.group(1)
    return "\n".join(kept)


def is_push(command: str) -> bool:
    return bool(PUSH_RE.search(strip_heredocs(command)))


def hook_pre_bash(payload: dict) -> int:
    command = (payload.get("tool_input") or {}).get("command", "")
    if not is_push(command):
        return 0
    cfg = load_lanes()
    problems = []
    changed = write_build(cfg)
    stages_and_commits = re.search(r"\bgit\s+add\b", command) and re.search(r"\bgit\s+commit\b", command)
    if changed and not stages_and_commits:
        problems.append(f"Regenerated {len(changed)} spec file(s): {', '.join(changed)}. Commit them, then push again.")
    # Decisions already on main, or already present when this session began, are append-only.
    bases = [f"origin/{cfg['project']['defaultBranch']}", load_state().get("startHead")]
    errors, _ = validate(base=[b for b in bases if b and git_ok("rev-parse", "--verify", "--quiet", b)])
    errors = [e for e in errors if not e.startswith("Generated spec is out of date")] if changed else errors
    if errors:
        problems.append("Coordination check failed:\n  - " + "\n  - ".join(errors[:15]))
    lane = my_lane()
    if lane and not (COORD / "status" / f"{lane}.json").exists():
        problems.append(f"Lane {lane} has no status on this branch. Post one: python3 tools/coord.py status --summary '…'")
    return _deny("\n".join(problems)) if problems else 0


def _session_changes(cfg: dict) -> list:
    # startHead is recorded by the SessionStart hook. Without it, only
    # uncommitted changes count, so a session that never ran the hook is not
    # blamed for commits it inherited.
    start = load_state().get("startHead")
    changed = set()
    if start:
        diff = git_ok("diff", "-z", "--name-only", start, "HEAD") or ""
        changed |= {f for f in diff.split("\0") if f}
    porcelain = git_ok("status", "-z", "--porcelain", "--untracked-files=all") or ""
    for item in porcelain.split("\0"):
        if len(item) > 3 and item[2] == " ":
            changed.add(item[3:])
    return sorted(f for f in changed if (ROOT / f).is_file() and not is_generated(f, cfg))


def hook_stop(payload: dict) -> int:
    if payload.get("stop_hook_active"):
        return 0
    cfg = load_lanes()
    work = _session_changes(cfg)
    if not work:
        return 0
    lane = my_lane()
    problems = []
    if not lane:
        problems.append("Claim the lane this work belongs to: python3 tools/coord.py claim <lane> --purpose '…'")
    else:
        sid = session_ref()["id"]
        decisions = local_decisions()
        eff = effective_status(decisions)
        if not any(rec.get("session", {}).get("id") == sid for rec in decisions.values()):
            problems.append("This session changed files but logged no decision. Record what you decided and what it produced: python3 tools/coord.py decide --title … --decision … --context … --produces …")
        uncovered = [f for f in work if not covering(f, decisions, eff)]
        if uncovered:
            problems.append("Not covered by any decision's --produces: " + ", ".join(uncovered[:10]))
        status_path = COORD / "status" / f"{lane}.json"
        newest = max((ROOT / f).stat().st_mtime for f in work)
        status_time = None
        if status_path.exists():
            try:
                status_time = parse_iso(read_json(status_path).get("updatedAt"))
            except ValueError:
                status_time = None
        if status_time is None or status_time.timestamp() < newest - 5:
            problems.append("Your lane status predates your latest change. Update it: python3 tools/coord.py status --summary … --now … --next …")
        expected = build_outputs(cfg, decisions)
        if any(not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text for p, text in expected.items()):
            problems.append("Spec is stale: python3 tools/coord.py build")
    if problems:
        print("[coord] Before you stop, close the loop:\n- " + "\n- ".join(problems) + "\nThen commit and push your branch.", file=sys.stderr)
        return 2
    return 0


HOOKS = {
    "session-start": hook_session_start,
    "prompt": hook_prompt,
    "pre-edit": hook_pre_edit,
    "pre-bash": hook_pre_bash,
    "stop": hook_stop,
}


def cmd_hook(args):
    if os.environ.get("PEAK_COORD", "").lower() in ("off", "0", "false"):
        return 0
    try:
        raw = sys.stdin.read() if not sys.stdin.isatty() else ""
        payload = json.loads(raw) if raw.strip() else {}
    except ValueError:
        payload = {}
    try:
        return HOOKS[args.event](payload)
    except Exception as exc:  # a coordination bug must never wedge a session
        print(f"[coord] {args.event} hook error, ignored: {exc}", file=sys.stderr)
        return 0


