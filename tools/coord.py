def log_event(lane: str, kind: str, ref: str, summary: str) -> None:
    event = {"ts": now_iso(), "lane": lane, "kind": kind, "ref": ref, "summary": summary[:240], "session": session_ref()["id"]}
    path = COORD / "events" / f"{lane}.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(event, ensure_ascii=False) + "\n")


def touch_session(lane: str, purpose=None) -> Path:
    ref = session_ref()
    path = COORD / "sessions" / f"{lane}--{safe_name(ref['id'])}.json"
    previous = {}
    if path.exists():
        try:
            previous = read_json(path)
        except (OSError, ValueError):
            previous = {}
    stamp = now_iso()
    record = {
        "schemaVersion": 1,
        "sessionId": ref["id"],
        "url": ref["url"],
        "lane": lane,
        "branch": ref["branch"],
        "purpose": purpose if purpose is not None else previous.get("purpose", ""),
        "startedAt": previous.get("startedAt", stamp),
        "lastSeenAt": stamp,
    }
    write_text(path, dumps(record))
    return path


def build_outputs(cfg=None, decisions=None, files=None) -> dict:
    """Every generated file and its exact content. Deterministic: no clocks."""
    cfg = cfg or load_lanes()
    decisions = local_decisions() if decisions is None else decisions
    files = repo_files() if files is None else files
    eff = effective_status(decisions)
    outputs = {}
    for lane in cfg["lanes"]:
        lid = lane["id"]
        rows = []
        for path in files:
            if is_generated(path, cfg) or owner_of(path, cfg) != lid:
                continue
            rows.append({"path": path, "sha256": sha256_file(ROOT / path), "decisions": covering(path, decisions, eff)})
        outputs[f"coord/trace/{lid}.json"] = dumps({"schemaVersion": 1, "lane": lid, "files": rows})
        outputs[f"spec/{lid}.md"] = render_lane_spec(lane, cfg, decisions, eff, rows)
    outputs["spec/README.md"] = render_spec_index(cfg)
    return outputs


def write_build(cfg=None) -> list:
    """Write generated files; return the paths that changed."""
    cfg = cfg or load_lanes()
    outputs = build_outputs(cfg)
    changed = []
    for path, text in outputs.items():
        target = ROOT / path
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            write_text(target, text)
            changed.append(path)
    for folder, suffix in (("coord/trace", ".json"), ("spec", ".md")):
        for stale in sorted((ROOT / folder).glob(f"*{suffix}")):
            if rel(stale) not in outputs:
                stale.unlink()
                changed.append(rel(stale) + " (removed)")
    return changed


# ---------------------------------------------------------------------------
# Spec rendering


def _md_session(session: dict) -> str:
    if not session:
        return "session unknown"
    if session.get("url"):
        return f"[session]({session['url']})"
    return f"session `{session.get('id')}`"


def _md_decision(rec: dict, eff: dict, sup_by: dict) -> list:
    did = rec["id"]
    meta = [f"`{eff.get(did, rec.get('status'))}`", rec.get("type", ""), rec.get("createdAt", "")[:10], _md_session(rec.get("session"))]
    if rec.get("session", {}).get("branch"):
        meta.append(f"branch `{rec['session']['branch']}`")
    if rec.get("acceptedBy"):
        meta.append(f"accepted by {rec['acceptedBy']}")
    lines = [f"### {did} · {rec.get('title', '')}", "", " · ".join(m for m in meta if m), "", f"**Decision.** {rec.get('decision', '').strip()}", "", f"**Context.** {rec.get('context', '').strip()}", ""]
    if rec.get("alternatives"):
        lines += ["**Alternatives considered.**", ""] + [f"- {alt}" for alt in rec["alternatives"]] + [""]
    if rec.get("consequences"):
        lines += [f"**Consequences.** {rec['consequences'].strip()}", ""]
    links = []
    if rec.get("produces"):
        links.append("**Produces:** " + ", ".join(f"`{p}`" for p in rec["produces"]))
    if rec.get("dependsOn"):
        links.append("**Depends on:** " + ", ".join(rec["dependsOn"]))
    if rec.get("supersedes"):
        links.append("**Supersedes:** " + ", ".join(rec["supersedes"]))
    if sup_by.get(did):
        links.append("**Superseded by:** " + ", ".join(sup_by[did]))
    if links:
        lines += ["  \n".join(links), ""]
    return lines


def render_lane_spec(lane: dict, cfg: dict, decisions: dict, eff: dict, rows: list) -> str:
    lid = lane["id"]
    sup_by = superseded_by(decisions)
    own = [decisions[d] for d in sorted(decisions) if decisions[d].get("lane") == lid]
    in_force = [r for r in own if eff[r["id"]] == "accepted"]
    proposed = [r for r in own if eff[r["id"]] == "proposed"]
    retired = [r for r in own if eff[r["id"]] in ("superseded", "rejected")]
    foreign = sorted({d for row in rows for d in row["decisions"] if decisions.get(d, {}).get("lane") != lid})
    lines = [
        f"# {lane['name']} (`{lid}`)",
        "",
        f"> {GENERATED_NOTE} The live view across every branch is the dashboard.",
        "",
        lane["mission"],
        "",
        "**Owns:** " + ", ".join(f"`{p}`" for p in lane["owns"]) + "  ",
        "**Depends on:** " + (", ".join(f"`{d}`" for d in lane["dependsOn"]) or "nothing") + "  ",
        f"**Brief:** [docs/hackathon/lanes/{lid}.md](../docs/hackathon/lanes/{lid}.md)",
        "",
        "## Deliverables",
        "",
    ]
    lines += [f"- {item}" for item in lane["deliverables"]] + [""]
    lines += ["## Decisions in force", ""]
    if in_force:
        for rec in in_force:
            lines += _md_decision(rec, eff, sup_by)
    else:
        lines += ["None yet.", ""]
    lines += ["## Proposed, awaiting acceptance", ""]
    if proposed:
        for rec in proposed:
            lines += _md_decision(rec, eff, sup_by)
    else:
        lines += ["None.", ""]
    lines += ["## Superseded and rejected", ""]
    if retired:
        for rec in retired:
            note = f" (superseded by {', '.join(sup_by[rec['id']])})" if sup_by.get(rec["id"]) else ""
            lines.append(f"- {rec['id']} · {rec.get('title', '')} · `{eff[rec['id']]}`{note}")
        lines.append("")
    else:
        lines += ["None.", ""]
    if foreign:
        lines += ["## Decisions from other lanes that cover files here", ""]
        lines += [f"- {d} · {decisions[d].get('title', '')} (`{decisions[d].get('lane')}`)" for d in foreign] + [""]
    lines += ["## Produced artifacts", "", "Every file this lane owns, the first 12 hex digits of its SHA-256 at build time, and the decisions that cover it.", ""]
    if rows:
        lines += ["| File | sha256 | Decisions |", "|---|---|---|"]
        for row in rows:
            lines.append(f"| `{row['path']}` | `{row['sha256'][:12]}` | {', '.join(row['decisions']) or '**uncovered**'} |")
        lines.append("")
    else:
        lines += ["No files yet.", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_spec_index(cfg: dict) -> str:
    project = cfg["project"]
    lines = [
        f"# {project['name']} spec",
        "",
        f"> {GENERATED_NOTE}",
        "",
        "The spec is the decision log rendered per lane. Each lane file lists the decisions in force, the proposals waiting on someone, and every file the lane owns with the hash it had when the spec was built and the decisions that cover it. A file no decision covers fails CI.",
        "",
        "Each branch carries the spec for its own state. The dashboard merges every branch into one live view"
        + (f": {project['dashboardUrl']}" if project.get("dashboardUrl") else "."),
        "",
        "| Lane | Mission | Spec |",
        "|---|---|---|",
    ]
    for lane in cfg["lanes"]:
        lines.append(f"| `{lane['id']}` {lane['name']} | {lane['mission']} | [{lane['id']}.md]({lane['id']}.md) |")
    return "\n".join(lines) + "\n"


