def cmd_validate(args):
    errors, warnings = validate(base=args.base)
    for warning in warnings:
        print(f"warning: {warning}")
    for error in errors:
        print(f"ERROR: {error}")
    if errors:
        print(f"\n{len(errors)} error(s). The protocol is in coord/README.md.")
        return 1
    print(f"Coordination checks passed ({len(warnings)} warning(s)).")
    return 0


def site_data(view: dict) -> dict:
    cfg = view["lanes"]
    decisions = view_decisions(view)
    eff = effective_status(decisions)
    sup_by = superseded_by(decisions)
    decision_rows = []
    for did, entry in view["decisions"].items():
        rec = entry["record"]
        decision_rows.append({**rec, "effectiveStatus": eff[did], "supersededBy": sup_by.get(did, []), "branches": sorted(set(entry["branches"])), "conflict": len(entry["bodies"]) > 1})
    decision_rows.sort(key=lambda r: r.get("createdAt", ""), reverse=True)
    trace = {}
    for lane in cfg["lanes"]:
        picked = pick_trace(view, lane["id"])
        trace[lane["id"]] = picked["files"] if picked else []
    events = sorted(view["events"].values(), key=lambda e: e.get("ts", ""), reverse=True)[:400]
    return {
        "schemaVersion": 1,
        "generatedAt": now_iso(),
        "project": cfg["project"],
        "lanes": cfg["lanes"],
        "status": view["status"],
        "decisions": decision_rows,
        "messages": sorted(view["messages"].values(), key=lambda m: m.get("createdAt", ""), reverse=True)[:300],
        "sessions": sorted(view["sessions"].values(), key=lambda s: s.get("lastSeenAt", ""), reverse=True),
        "events": events,
        "trace": trace,
        "branches": [{"name": b["name"], "sha": b["sha"][:7], "committedAt": b["committedAt"], "subject": b["subject"]} for b in view["branches"]],
        "parseErrors": view["parseErrors"],
    }


def cmd_site(args):
    view = collect(fetch_first=not args.no_fetch, include_worktree=not args.refs_only)
    data = site_data(view)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
