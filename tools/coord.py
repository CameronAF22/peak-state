    payload = json.dumps(data, ensure_ascii=False, indent=1)
    write_text(out / "data.json", payload + "\n")
    if args.fragment:
        inline = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
        page = template.replace("<!--PEAK_INLINE_DATA-->", f"<script>window.__PEAK_DATA__ = {inline};</script>")
        write_text(out / "dashboard.html", page)
        print(f"Wrote {out / 'dashboard.html'} and data.json ({len(data['decisions'])} decisions, {len(data['branches'])} branches)")
    else:
        page = (
            '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n</head>\n<body>\n'
            + template
            + "\n</body>\n</html>\n"
        )
        write_text(out / "index.html", page)
        print(f"Wrote {out / 'index.html'} and data.json ({len(data['decisions'])} decisions, {len(data['branches'])} branches)")


