# Identity


def session_ref() -> dict:
    """The session writing a record. Cloud sessions carry a reopenable URL."""
    remote = os.environ.get("CLAUDE_CODE_REMOTE_SESSION_ID", "").strip()
    if remote:
        tail = remote.split("_", 1)[1] if "_" in remote else remote
        return {
            "id": f"session_{tail}",
            "url": f"https://claude.ai/code/session_{tail}",
            "branch": current_branch(),
        }
    sid = (
        os.environ.get("PEAK_SESSION_ID")
        or os.environ.get("CLAUDE_CODE_SESSION_ID")
        or f"local-{os.environ.get('USER', 'human')}"
    )
    return {"id": sid, "url": None, "branch": current_branch()}


def safe_name(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]", "-", value)[:80]


# ---------------------------------------------------------------------------
# Lanes and ownership


def load_lanes() -> dict:
    path = COORD / "lanes.json"
    if not path.exists():
        raise CoordError("coord/lanes.json is missing")
    return read_json(path)


def lane_map(cfg: dict) -> dict:
    return {lane["id"]: lane for lane in cfg["lanes"]}


def path_matches(path: str, pattern: str) -> bool:
    if pattern.endswith("/"):
        return path.startswith(pattern)
    if any(ch in pattern for ch in "*?["):
        return fnmatch.fnmatchcase(path, pattern)
    return path == pattern


def owner_of(path: str, cfg: dict):
    """The lane owning a path: the longest matching `owns` entry wins."""
    best, best_len = None, -1
    for lane in cfg["lanes"]:
        for pattern in lane["owns"]:
            if path_matches(path, pattern) and len(pattern) > best_len:
                best, best_len = lane["id"], len(pattern)
    return best


def is_generated(path: str, cfg: dict) -> bool:
    return any(path.startswith(prefix) for prefix in cfg.get("generated", []))


def my_lane():
    env = os.environ.get("PEAK_LANE", "").strip()
    if env:
        return env
    state = load_state()
    if state.get("lane"):
        return state["lane"]
    # A resumed session in a fresh container finds its lane in the registry.
    sid = session_ref()["id"]
    for path in sorted((COORD / "sessions").glob("*.json")):
        try:
            record = read_json(path)
        except (OSError, ValueError):
            continue
        if record.get("sessionId") == sid:
            return record.get("lane")
    return None


def require_lane(cfg: dict) -> str:
    lane = my_lane()
    if not lane:
        raise CoordError(
            "No lane claimed. Run: python3 tools/coord.py claim <lane> --purpose '<one line>'. "
            f"Lanes: {', '.join(lane_map(cfg))}"
        )
    if lane not in lane_map(cfg):
        raise CoordError(f"Claimed lane '{lane}' is not in coord/lanes.json")
    return lane


def repo_files() -> list:
    out = git("ls-files", "-z", "--cached", "--others", "--exclude-standard")
    return sorted({f for f in out.split("\0") if f and (ROOT / f).is_file()})


# ---------------------------------------------------------------------------
# A small JSON Schema validator: the subset schemas/coord/ uses.

_SCHEMA_CACHE: dict = {}


def load_schema(name: str) -> dict:
    if name not in _SCHEMA_CACHE:
        _SCHEMA_CACHE[name] = read_json(SCHEMAS / f"{name}.schema.json")
    return _SCHEMA_CACHE[name]


def _type_ok(value, kind: str) -> bool:
    if kind == "object":
        return isinstance(value, dict)
    if kind == "array":
        return isinstance(value, list)
    if kind == "string":
        return isinstance(value, str)
    if kind == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if kind == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if kind == "boolean":
        return isinstance(value, bool)
    if kind == "null":
        return value is None
    return False


def schema_errors(value, schema: dict, root=None, where="$") -> list:
    root = root or schema
    if "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith("#/$defs/"):
            return [f"{where}: unsupported $ref {ref}"]
        return schema_errors(value, root["$defs"][ref[len("#/$defs/"):]], root, where)
    errors = []
    if "anyOf" in schema and all(schema_errors(value, sub, root, where) for sub in schema["anyOf"]):
        errors.append(f"{where}: matches none of the allowed shapes")
    if "const" in schema and value != schema["const"]:
        errors.append(f"{where}: must be {schema['const']!r}")
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{where}: must be one of {', '.join(map(str, schema['enum']))}")
    if "type" in schema:
        kinds = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
        if not any(_type_ok(value, kind) for kind in kinds):
            return errors + [f"{where}: expected {' or '.join(kinds)}"]
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errors.append(f"{where}: must not be empty" if schema.get("minLength") == 1 else f"{where}: too short")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            errors.append(f"{where}: longer than {schema['maxLength']} characters")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errors.append(f"{where}: does not match {schema['pattern']}")
        if schema.get("format") == "date-time" and not parse_iso(value):
            errors.append(f"{where}: not an ISO 8601 date-time")
    if _type_ok(value, "number"):
        if "minimum" in schema and value < schema["minimum"]:
            errors.append(f"{where}: below {schema['minimum']}")
        if "maximum" in schema and value > schema["maximum"]:
            errors.append(f"{where}: above {schema['maximum']}")
    if isinstance(value, dict):
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{where}: missing '{key}'")
        props = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        for key, item in value.items():
            if key in props:
                errors += schema_errors(item, props[key], root, f"{where}.{key}")
            elif extra is False:
                errors.append(f"{where}: unexpected field '{key}'")
            elif isinstance(extra, dict):
                errors += schema_errors(item, extra, root, f"{where}.{key}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{where}: needs at least {schema['minItems']} item(s)")
        if schema.get("uniqueItems") and len({json.dumps(v, sort_keys=True) for v in value}) != len(value):
            errors.append(f"{where}: items must be unique")
        if "items" in schema:
            for index, item in enumerate(value):
                errors += schema_errors(item, schema["items"], root, f"{where}[{index}]")
    return errors


# ---------------------------------------------------------------------------
# Decisions


def local_decisions() -> dict:
    decisions = {}
    for path in sorted((COORD / "decisions").glob("*/D-*.json")):
        try:
            record = read_json(path)
        except (OSError, ValueError):
            continue
        decisions[record.get("id", path.stem)] = record
    return decisions


def effective_status(decisions: dict) -> dict:
    """Stored status, except a decision named in a live `supersedes` is superseded."""
    status = {did: rec.get("status", "proposed") for did, rec in decisions.items()}
    for rec in decisions.values():
        if rec.get("status") == "rejected":
            continue
        for old in rec.get("supersedes", []):
            if old in status and status[old] != "rejected":
                status[old] = "superseded"
    return status


def superseded_by(decisions: dict) -> dict:
    out = defaultdict(list)
    for did, rec in sorted(decisions.items()):
        if rec.get("status") != "rejected":
            for old in rec.get("supersedes", []):
                out[old].append(did)
    return out


def covering(path: str, decisions: dict, eff: dict) -> list:
    return sorted(
        did
        for did, rec in decisions.items()
        if eff.get(did) != "rejected" and any(path_matches(path, p) for p in rec.get("produces", []))
    )


def next_decision_id(lane: str, known_ids) -> str:
    numbers = []
    for did in known_ids:
        match = DECISION_ID_RE.match(did)
        if match and match.group(1) == lane:
            numbers.append(int(match.group(2)))
    return f"D-{lane}-{(max(numbers) + 1 if numbers else 1):03d}"


