def validate(base=None):
    errors, warnings = [], []
    cfg = load_lanes()
    errors += [f"coord/lanes.json {e}" for e in schema_errors(cfg, load_schema("lanes"))]
    if errors:
        return errors, warnings
    ids = set(lane_map(cfg))
    seen_patterns = {}
    for lane in cfg["lanes"]:
        for pattern in lane["owns"]:
            if pattern in seen_patterns:
                errors.append(f"coord/lanes.json: '{pattern}' is owned by both {seen_patterns[pattern]} and {lane['id']}")
            seen_patterns[pattern] = lane["id"]
        for dep in lane["dependsOn"]:
            if dep not in ids:
                errors.append(f"coord/lanes.json: lane {lane['id']} depends on unknown lane {dep}")

    files = repo_files()
    decisions = {}
    for path in files:
        match = DECISION_PATH_RE.match(path)
        if match:
            try:
                record = read_json(ROOT / path)
            except ValueError as exc:
                errors.append(f"{path}: invalid JSON ({exc})")
                continue
            errors += [f"{path} {e}" for e in schema_errors(record, load_schema("decision"))]
            did, lane = record.get("id", ""), record.get("lane")
            expected = f"coord/decisions/{lane}/{did}.json"
            if path != expected:
                errors.append(f"{path}: must live at {expected}")
            if lane not in ids:
                errors.append(f"{path}: unknown lane '{lane}'")
            id_match = DECISION_ID_RE.match(did)
            if id_match and id_match.group(1) != lane:
                errors.append(f"{path}: id {did} does not belong to lane {lane}")
            if did in decisions:
                errors.append(f"{path}: duplicate decision id {did}")
            decisions[did] = record
        elif path.startswith("coord/decisions/"):
            errors.append(f"{path}: only coord/decisions/<lane>/D-<lane>-NNN.json files belong here")
        elif path.startswith("coord/status/"):
            record = _load_for_validation(path, errors)
            if record is not None:
                errors += [f"{path} {e}" for e in schema_errors(record, load_schema("status"))]
                if path != f"coord/status/{record.get('lane')}.json":
                    errors.append(f"{path}: file name must match its lane")
        elif path.startswith("coord/messages/"):
            record = _load_for_validation(path, errors)
            if record is not None:
                errors += [f"{path} {e}" for e in schema_errors(record, load_schema("message"))]
                if record.get("to") not in ids | set(SPECIAL_RECIPIENTS):
                    errors.append(f"{path}: unknown recipient '{record.get('to')}'")
        elif path.startswith("coord/sessions/"):
            record = _load_for_validation(path, errors)
            if record is not None:
                errors += [f"{path} {e}" for e in schema_errors(record, load_schema("session"))]
        elif path.startswith("coord/events/"):
            for number, line in enumerate((ROOT / path).read_text(encoding="utf-8").splitlines(), 1):
                if not line.strip():
                    continue
                try:
                    event = json.loads(line)
                except ValueError:
                    errors.append(f"{path}:{number}: invalid JSON")
                    continue
                errors += [f"{path}:{number} {e}" for e in schema_errors(event, load_schema("event"))]

    for did, record in sorted(decisions.items()):
        for ref in record.get("dependsOn", []) + record.get("supersedes", []):
            if ref not in decisions:
                warnings.append(f"{did} references {ref}, which is not on this branch (fine if it lives on another lane's branch)")
        for pattern in record.get("produces", []):
            if ".." in pattern.split("/"):
                errors.append(f"{did}: produces entry '{pattern}' leaves the repository")
            elif not any(path_matches(f, pattern) for f in files):
                warnings.append(f"{did}: produces '{pattern}', which does not exist yet")

    eff = effective_status(decisions)
    uncovered = defaultdict(list)
    for path in files:
        if is_generated(path, cfg):
            continue
        owner = owner_of(path, cfg)
        if owner is None:
            errors.append(f"{path}: no lane owns this path. Move it under your lane's paths or ask coord to extend coord/lanes.json")
            continue
        if not covering(path, decisions, eff):
            uncovered[owner].append(path)
    for lane, paths in sorted(uncovered.items()):
        shown = ", ".join(paths[:12]) + (" …" if len(paths) > 12 else "")
        errors.append(
            f"{len(paths)} file(s) owned by lane '{lane}' are not covered by any decision: {shown}. "
            "Log the decision that produced them: python3 tools/coord.py decide … --produces <paths>"
        )

    expected = build_outputs(cfg, decisions, files)
    stale = sorted(p for p, text in expected.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != text)
    stale += sorted(f"{p} (orphan)" for p in files if (p.startswith("coord/trace/") or p.startswith("spec/")) and p not in expected)
    if stale:
        errors.append("Generated spec is out of date: " + ", ".join(stale) + ". Run: python3 tools/coord.py build")

    for ref in ([base] if isinstance(base, str) else list(base or [])):
        errors += [e for e in _immutability_errors(ref) if e not in errors]
    return errors, warnings


def _load_for_validation(path: str, errors: list):
    try:
        return read_json(ROOT / path)
    except ValueError as exc:
        errors.append(f"{path}: invalid JSON ({exc})")
        return None


def _immutability_errors(base: str) -> list:
    """Decisions present at the merge base with `base` may only change status."""
    merge_base = (git_ok("merge-base", "HEAD", base) or "").strip()
    if not merge_base:
        return []
    errors = []
    listing = git_ok("ls-tree", "-r", "--name-only", merge_base, "--", "coord/decisions/") or ""
    for path in listing.splitlines():
        if not DECISION_PATH_RE.match(path):
            continue
        current = ROOT / path
        if not current.exists():
            errors.append(f"{path}: decisions are append-only and this one was deleted. Supersede it instead.")
            continue
        try:
            old = json.loads(git("show", f"{merge_base}:{path}"))
            new = read_json(current)
        except (ValueError, CoordError):
            continue
        strip = lambda record: {k: v for k, v in record.items() if k not in MUTABLE_DECISION_FIELDS}  # noqa: E731
        if strip(old) != strip(new):
            errors.append(f"{path}: decisions are immutable except status. Write a new decision with --supersedes {old.get('id')} instead.")
    return errors


