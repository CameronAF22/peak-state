def render_board(view: dict, lane=None, decisions_limit=8) -> str:
    cfg = view["lanes"]
    decisions = view_decisions(view)
    eff = effective_status(decisions)
    lines = ["LANES  (health · progress · last update · summary)"]
    for item in cfg["lanes"]:
        lid = item["id"]
        status = view["status"].get(lid)
        marker = "→" if lid == lane else " "
        if status:
            lines.append(
                f"{marker} {lid:<11} {status.get('health', '?'):<5} {status.get('progress', 0):>3}%  {ago(status.get('updatedAt')):>8}  {status.get('summary', '')[:110]}"
            )
            for blocker in status.get("blockers", [])[:3]:
                lines.append(f"      BLOCKER: {blocker[:120]}")
        else:
            lines.append(f"{marker} {lid:<11} —      no status yet")
        sessions = latest_sessions(view, lid)
        if sessions:
            s = sessions[0]
            lines.append(f"      session {s.get('url') or s.get('sessionId')} · branch {s.get('branch')} · seen {ago(s.get('lastSeenAt'))}")
    recent = sorted(decisions.values(), key=lambda r: r.get("createdAt", ""), reverse=True)[:decisions_limit]
    if recent:
        lines += ["", "RECENT DECISIONS"]
        for rec in recent:
            lines.append(f"  {rec['id']:<18} [{eff.get(rec['id'])}] {rec.get('title', '')[:90]} · {ago(rec.get('createdAt'))}")
    waiting = [r for r in decisions.values() if eff.get(r["id"]) == "proposed"]
    if waiting:
        lines += ["", "PROPOSED, WAITING FOR ACCEPTANCE"]
        for rec in sorted(waiting, key=lambda r: r["id"]):
            lines.append(f"  {rec['id']:<18} {rec.get('title', '')[:100]}")
    conflicts = [did for did, entry in view["decisions"].items() if len(entry["bodies"]) > 1]
    if conflicts:
        lines += ["", "CONFLICTING DECISION IDS (same id, different content on different branches): " + ", ".join(sorted(conflicts))]
    return "\n".join(lines)


def render_message(msg: dict) -> str:
    refs = f" refs {', '.join(msg['refs'])}" if msg.get("refs") else ""
    return f"  {msg['id']} · {msg.get('from')} → {msg.get('to')} · {ago(msg.get('createdAt'))}{refs}\n    {msg.get('subject')}: {msg.get('body', '')[:400]}"


