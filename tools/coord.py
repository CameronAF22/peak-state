# Reading every branch


def fetch(force=False, max_age=FETCH_MAX_AGE) -> bool:
    state = load_state()
    if not force and time.time() - state.get("lastFetch", 0) < max_age:
        return True
    ok = git_ok("fetch", "--quiet", "--prune", "origin", "+refs/heads/*:refs/remotes/origin/*", timeout=30) is not None
    update_state(lastFetch=time.time(), lastFetchOk=ok)
    return ok


def remote_refs() -> list:
    out = git_ok(
        "for-each-ref",
        "--sort=-committerdate",
        "--format=%(refname)%09%(objectname)%09%(committerdate:iso-strict)%09%(subject)",
        "refs/remotes/origin",
    ) or ""
    refs = []
    for line in out.splitlines():
        parts = line.split("\t", 3)
        if len(parts) < 4 or parts[0].endswith("/HEAD"):
            continue
        refs.append({"name": parts[0][len("refs/remotes/origin/"):], "ref": parts[0], "sha": parts[1], "committedAt": parts[2], "subject": parts[3]})
    return refs


def tree_entries(ref: str, prefix="coord/") -> list:
    out = git_ok("ls-tree", "-r", "-z", ref, "--", prefix) or ""
    entries = []
    for item in out.split("\0"):
        if not item or "\t" not in item:
            continue
        meta, path = item.split("\t", 1)
        parts = meta.split()
        if len(parts) == 3 and parts[1] == "blob":
            entries.append((path, parts[2]))
    return entries


def read_blobs(shas) -> dict:
    shas = sorted(set(shas))
    if not shas:
        return {}
    result = subprocess.run(
        ["git", "-C", str(ROOT), "cat-file", "--batch"],
        input=("\n".join(shas) + "\n").encode(),
        capture_output=True,
        timeout=60,
    )
    data, out, i = result.stdout, {}, 0
    while i < len(data):
        newline = data.index(b"\n", i)
        header = data[i:newline].decode().split()
        i = newline + 1
        if len(header) < 3:
            continue
        size = int(header[2])
        out[header[0]] = data[i : i + size].decode("utf-8", "replace")
        i += size + 1
    return out


def collect(fetch_first=False, include_worktree=True) -> dict:
    """Merge coord/ records from the working tree and every remote branch."""
    fetched = fetch() if fetch_first else None
    refs = remote_refs()
    sources = []
    if include_worktree and COORD.is_dir():
        files = {rel(p): p.read_text(encoding="utf-8", errors="replace") for p in sorted(COORD.rglob("*")) if p.is_file()}
        sources.append(("worktree", files))
    entries = {r["name"]: tree_entries(r["ref"]) for r in refs}
    blobs = read_blobs(sha for es in entries.values() for _, sha in es)
    for r in refs:
        sources.append((r["name"], {path: blobs.get(sha, "") for path, sha in entries[r["name"]]}))

    view = {
        "decisions": {}, "status": {}, "sessions": {}, "messages": {}, "events": {}, "trace": defaultdict(dict),
        "lanes": None, "branches": refs, "parseErrors": [], "fetched": fetched,
    }
    lanes_by_source = {}
    for label, files in sources:
        for path, text in files.items():
            if path.endswith(".jsonl") and path.startswith("coord/events/"):
                for line in text.splitlines():
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        event = json.loads(line)
                    except ValueError:
                        continue
                    key = json.dumps(event, sort_keys=True)
                    view["events"].setdefault(key, {**event, "branch": label})
                continue
            if not path.endswith(".json"):
                continue
            try:
                record = json.loads(text)
            except ValueError:
                view["parseErrors"].append(f"{label}:{path}")
                continue
            if path == "coord/lanes.json":
                lanes_by_source[label] = record
            elif DECISION_PATH_RE.match(path):
                _merge_decision(view["decisions"], record, label)
            elif path.startswith("coord/status/"):
                lane = record.get("lane")
                prev = view["status"].get(lane)
                if lane and (not prev or record.get("updatedAt", "") > prev.get("updatedAt", "")):
                    view["status"][lane] = {**record, "branchSeen": label}
            elif path.startswith("coord/sessions/"):
                key = Path(path).name
                prev = view["sessions"].get(key)
                if not prev or record.get("lastSeenAt", "") > prev.get("lastSeenAt", ""):
                    view["sessions"][key] = record
            elif path.startswith("coord/messages/"):
                view["messages"].setdefault(record.get("id", path), {**record, "branchSeen": label})
            elif path.startswith("coord/trace/"):
                view["trace"][record.get("lane")][label] = record
    for preferred in ("worktree", "main"):
        if preferred in lanes_by_source:
            view["lanes"] = lanes_by_source[preferred]
            break
    else:
        view["lanes"] = next(iter(lanes_by_source.values()), None)
    if view["lanes"] is None:
        view["lanes"] = load_lanes()
    return view


def _merge_decision(store: dict, record: dict, label: str) -> None:
    did = record.get("id")
    if not did:
        return
    body = json.dumps({k: v for k, v in record.items() if k not in MUTABLE_DECISION_FIELDS}, sort_keys=True)
    entry = store.get(did)
    if entry is None:
        store[did] = {"record": record, "branches": [label], "bodies": {body}}
        return
    entry["branches"].append(label)
    entry["bodies"].add(body)
    if STATUS_RANK.get(record.get("status"), 0) > STATUS_RANK.get(entry["record"].get("status"), 0):
        entry["record"] = record


def view_decisions(view: dict) -> dict:
    return {did: entry["record"] for did, entry in view["decisions"].items()}


def pick_trace(view: dict, lane: str):
    variants = view["trace"].get(lane, {})
    if not variants:
        return None
    status = view["status"].get(lane)
    for label in ("worktree", (status or {}).get("branchSeen"), (status or {}).get("session", {}).get("branch"), "main"):
        if label and label in variants:
            return variants[label]
    return next(iter(variants.values()))


def latest_sessions(view: dict, lane: str) -> list:
    sessions = [s for s in view["sessions"].values() if s.get("lane") == lane]
    return sorted(sessions, key=lambda s: s.get("lastSeenAt", ""), reverse=True)


def inbox_for(view: dict, lane: str) -> list:
    msgs = [m for m in view["messages"].values() if m.get("to") in (lane, "all") and m.get("from") != lane]
    return sorted(msgs, key=lambda m: m.get("createdAt", ""), reverse=True)


