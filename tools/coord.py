#!/usr/bin/env python3
"""Peak State coordination CLI and Claude Code hook handler.

Lanes write every coordination record (decisions, status, messages, session
claims, events) through this tool, never by hand, so each record matches its
contract in schemas/coord/ and the generated spec (spec/, coord/trace/) can be
rebuilt byte for byte from the repository. Standard library only, so the hooks
run in any container without an install step.

Agents read across lanes without merging: every lane pushes to its own
branch, and `board`, `inbox`, `show`, `why` and `context` read the coord/
records of every remote branch straight out of git.

Protocol: coord/README.md. Agent rules: CLAUDE.md.
"""

