ROOT = Path(__file__).resolve().parent.parent
COORD = ROOT / "coord"
SCHEMAS = ROOT / "schemas" / "coord"
DECISION_ID_RE = re.compile(r"^D-([a-z][a-z0-9-]{1,23})-(\d{3})$")
DECISION_PATH_RE = re.compile(r"^coord/decisions/([^/]+)/([^/]+)\.json$")
GENERATED_NOTE = "Generated by `python3 tools/coord.py build` from coord/lanes.json and coord/decisions/. Do not edit by hand."
FETCH_MAX_AGE = 90  # seconds between automatic fetches triggered by hooks
STATUS_STALE_MINUTES = 45
MUTABLE_DECISION_FIELDS = {"status", "acceptedAt", "acceptedBy"}
STATUS_RANK = {"proposed": 0, "accepted": 1, "rejected": 1}
SPECIAL_RECIPIENTS = ("all", "human")


class CoordError(Exception):
    """A problem the person or agent running the command can fix."""


# ---------------------------------------------------------------------------
# Small helpers


def now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def parse_iso(value):
    if not isinstance(value, str) or "T" not in value:
        return None
    try:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def ago(value) -> str:
    dt = parse_iso(value)
    if not dt:
        return "never"
    secs = max(0, int((datetime.now(timezone.utc) - dt).total_seconds()))
    if secs < 60:
        return f"{secs}s ago"
    if secs < 3600:
        return f"{secs // 60}m ago"
    if secs < 86400:
        return f"{secs // 3600}h ago"
    return f"{secs // 86400}d ago"


def read_json(path: Path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def git(*args, check=True, timeout=60) -> str:
    try:
        result = subprocess.run(
            ["git", "-C", str(ROOT), *args], capture_output=True, text=True, timeout=timeout
        )
    except subprocess.TimeoutExpired as exc:
        raise CoordError(f"git {args[0]} timed out") from exc
    if check and result.returncode != 0:
        raise CoordError(f"git {' '.join(args)}: {(result.stderr or result.stdout).strip()}")
    return result.stdout


def git_ok(*args, timeout=60):
    try:
        return git(*args, timeout=timeout)
    except CoordError:
        return None


def current_branch():
    branch = (git_ok("rev-parse", "--abbrev-ref", "HEAD") or "").strip()
    return None if branch in ("", "HEAD") else branch


def head_sha():
    return (git_ok("rev-parse", "HEAD") or "").strip() or None


# ---------------------------------------------------------------------------
# Local, per-clone state (inside .git, never committed)


def state_file() -> Path:
    git_dir = Path((git_ok("rev-parse", "--git-dir") or ".git").strip())
    return (git_dir if git_dir.is_absolute() else ROOT / git_dir) / "peak-coord-state.json"


def load_state() -> dict:
    try:
        return read_json(state_file())
    except (OSError, ValueError):
        return {}


def save_state(state: dict) -> None:
    write_text(state_file(), dumps(state))


def update_state(**changes) -> dict:
    state = load_state()
    state.update(changes)
    save_state(state)
    return state


