def cmd_decide(args):
    cfg = load_lanes()
    lane = args.lane or require_lane(cfg)
    if lane not in lane_map(cfg):
        raise CoordError(f"Unknown lane '{lane}'")
    fields = {}
    if args.json:
        fields = json.load(sys.stdin) if args.json == "-" else read_json(Path(args.json))
    known = set(local_decisions()) | set(collect(include_worktree=False)["decisions"])
    did = next_decision_id(lane, known)
    status = _field(args, fields, "status", "accepted")
    record = {
        "schemaVersion": 1,
        "id": did,
        "lane": lane,
        "title": _field(args, fields, "title"),
        "status": status,
        "type": _field(args, fields, "type", "technical"),
        "context": _field(args, fields, "context"),
        "decision": _field(args, fields, "decision"),
        "alternatives": _field(args, fields, "alternatives", []),
        "consequences": _field(args, fields, "consequences", ""),
        "produces": _field(args, fields, "produces", []),
        "dependsOn": _field(args, fields, "dependsOn", []),
        "supersedes": _field(args, fields, "supersedes", []),
        "author": _field(args, fields, "author", os.environ.get("PEAK_AUTHOR", "claude")),
        "session": session_ref(),
        "createdAt": now_iso(),
    }
    if status == "accepted":
        record["acceptedAt"] = record["createdAt"]
        record["acceptedBy"] = record["author"]
    errors = schema_errors(record, load_schema("decision"))
    if errors:
        raise CoordError("Decision not written:\n  " + "\n  ".join(errors))
    path = COORD / "decisions" / lane / f"{did}.json"
    write_text(path, dumps(record))
    log_event(lane, "decision", did, f"[{status}] {record['title']}")
    touch_session(lane)
    write_build(cfg)
    print(f"{did} [{status}] {record['title']}\n  wrote {rel(path)} and rebuilt spec/{lane}.md")
    if lane != my_lane():
        print(f"  note: recorded in lane '{lane}', which is not your claimed lane")


